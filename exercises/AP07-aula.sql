SELECT E.EMPLOYEE_ID, E.JOB_ID AS CARGO_ATUAL,
    H.JOB_ID AS CARGO_ANTERIOR
FROM HR.EMPLOYEES AS E 
OUTER APPLY (
    SELECT TOP 1 J.JOB_ID
    FROM HR.job_history AS J
    WHERE J.EMPLOYEE_ID = E.EMPLOYEE_ID
    ORDER BY J.START_DATE DESC, J.END_DATE DESC
) AS H
WHERE E.EMPLOYEE_ID = 200;

