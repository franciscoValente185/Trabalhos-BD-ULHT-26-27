SELECT E.EMPLOYEE_ID, E.DEPARTMENT_ID,
    (SELECT D.DEPARTMENT_NAME
     FROM HR.DEPARTMENTS AS D 
     WHERE D.DEPARTMENT_ID = E.DEPARTMENT_ID) AS DEPARTMENT
FROM HR.EMPLOYEES AS E
ORDER BY E.EMPLOYEE_ID;

SELECT EMPLOYEE_ID, SALARY
FROM HR.EMPLOYEES
WHERE SALARY > (SELECT AVG(SALARY) FROM HR.EMPLOYEES)
ORDER BY SALARY DESC, EMPLOYEE_ID; 

SELECT AVG(SALARY) AS SALARIO_MEDIO
FROM HR.EMPLOYEES;

SELECT D.DEPARTMENT_ID, D.TOTAL, D.MEDIA
FROM (
    SELECT DEPARTMENT_ID, COUNT(*) AS TOTAL, AVG(SALARY) AS MEDIA
    FROM HR.EMPLOYEES
    WHERE DEPARTMENT_ID IS NOT NULL
    GROUP BY DEPARTMENT_ID
) AS D
WHERE D.TOTAL >= 3
ORDER BY D.MEDIA DESC, D.DEPARTMENT_ID;