SELECT E.FIRST_NAME, E.LAST_NAME, D.DEPARTMENT_NAME, D.DEPARTMENT_ID
FROM HR.EMPLOYEES AS E INNER JOIN HR.DEPARTMENTS AS D
ON E.department_id = D.department_id;

SELECT e.employee_id, d.department_id
FROM HR.employees AS e
RIGHT JOIN HR.departments AS d
ON e.department_id = d.department_id
ORDER BY d.department_id; 

SELECT e.employee_id, d.department_id
FROM HR.employees AS e
FULL OUTER JOIN HR.departments AS d
    ON e.department_id = d.department_id
WHERE e.employee_id IS NULL OR d.department_id IS NULL
ORDER BY d.department_id, e.employee_id;

SELECT E.EMPLOYEE_ID, E.FIRST_NAME,
    M.LAST_NAME AS MANAGER_LAST_NAME
FROM HR.EMPLOYEES AS E LEFT JOIN HR.EMPLOYEES AS M
    ON E.MANAGER_ID = M.EMPLOYEE_ID
ORDER BY E.EMPLOYEE_ID;

SELECT E.EMPLOYEE_ID, E.FIRST_NAME,
    L.CITY, C.COUNTRY_NAME
FROM HR.EMPLOYEES AS E LEFT JOIN HR.DEPARTMENTS AS D ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
LEFT JOIN HR.LOCATIONS AS L ON L.LOCATION_ID = D.LOCATION_ID
LEFT JOIN HR.COUNTRIES AS C ON C.COUNTRY_ID = L.COUNTRY_ID
ORDER BY E.EMPLOYEE_ID;

