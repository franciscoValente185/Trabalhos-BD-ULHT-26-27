SELECT HIRE_DATE, FIRST_NAME, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE HIRE_DATE < '2005-01-01' AND SALARY > 11000
ORDER BY HIRE_DATE;

SELECT JOB_ID, DEPARTMENT_ID, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID BETWEEN 20 AND 90 AND JOB_ID != 'AD_VP';

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE EMPLOYEE_ID BETWEEN 135 AND 145 AND EMPLOYEE_ID NOT IN (138, 140, 141);

SELECT EMPLOYEE_ID, JOB_ID, FIRST_NAME, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL AND JOB_ID != 'SA_MAN';

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE '%son';

SELECT JOB_ID, FIRST_NAME, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE JOB_ID LIKE 'ST%' AND JOB_ID LIKE '___C%';

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE LAST_NAME NOT LIKE '[A-M]%';

SELECT EMPLOYEE_ID, LAST_NAME, MANAGER_ID, DEPARTMENT_ID,
    IIF(DEPARTMENT_ID IS NULL, 'Reports to Manager', 'Has Department') AS MANAGER_STATUS
FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NOT NULL;

SELECT EMPLOYEE_ID, LAST_NAME, SALARY,
CASE
    WHEN SALARY < 3000 THEN 'Entry'
    WHEN SALARY < 6000 THEN 'Developing'
    WHEN SALARY < 10000 THEN 'Established'
    ELSE 'High'
END AS SALARY_LEVEL
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, DEPARTMENT_ID, LAST_NAME, SALARY,
CASE
    WHEN SALARY < 3000 THEN 'Entry'
    WHEN SALARY < 6000 THEN 'Developing'
    WHEN SALARY < 10000 THEN 'Established'
    ELSE 'High'
END AS SALARY_LEVEL
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (50, 80);

SELECT EMPLOYEE_ID, DEPARTMENT_ID, LAST_NAME, SALARY,
CASE
    WHEN DEPARTMENT_ID IN (10, 20, 30) THEN 'Group A'
    WHEN DEPARTMENT_ID IN (40, 50, 60) THEN 'Group B'
    ELSE 'Other'
END AS DEPT_GROUP
FROM HR.EMPLOYEES;

SELECT EMPLOYEE_ID, COMMISSION_PCT, LAST_NAME, 
    IIF(COMMISSION_PCT IS NULL, 'Missing', 'Recorded') AS COMMISSION_STATUS
FROM HR.EMPLOYEES;

SELECT PHONE_NUMBER, LAST_NAME,
    CASE
        WHEN PHONE_NUMBER NOT LIKE '[1-6]%' THEN 'Outside Expected Prefix'
        WHEN PHONE_NUMBER IS NULL THEN 'Missing'
        ELSE 'Expected Prefix'
    END AS PHONE_ISSUE
FROM HR.EMPLOYEES;

SELECT PHONE_NUMBER, LAST_NAME, HIRE_DATE,
    CASE
        WHEN PHONE_NUMBER NOT LIKE '[1-6]%' THEN 'Outside Expected Prefix'
        WHEN PHONE_NUMBER IS NULL THEN 'Missing'
        ELSE 'Expected Prefix'
    END AS PHONE_ISSUE
FROM HR.EMPLOYEES
WHERE HIRE_DATE BETWEEN '2004-01-01' AND '2007-12-31'
ORDER BY HIRE_DATE;

WITH Candidates AS (
    SELECT
        EMPLOYEE_ID,
        LOWER(LEFT(FIRST_NAME, 1) + '.' + LAST_NAME) AS CANDIDATE
    FROM HR.EMPLOYEES
)
SELECT
    EMPLOYEE_ID,
    CANDIDATE,
    CASE
        WHEN CANDIDATE LIKE '%''%' THEN 'Apóstrofo'
        WHEN CANDIDATE LIKE '%-%' THEN 'Hífen'
    END AS CHARACTER_FOUND
FROM Candidates
WHERE CANDIDATE LIKE '%''%'
   OR CANDIDATE LIKE '%-%';