SELECT DEPARTMENT_ID, MIN(SALARY) AS MIN_SALARY, MAX(SALARY) AS MAX_SALARY, 
    MAX(SALARY) - MIN(SALARY) AS SALARY_RANGE
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY SALARY_RANGE DESC;

SELECT 
    IIF(COMMISSION_PCT IS NULL, 'No Commission', 'Commission') AS COMMISSION_CATEGORY,
    COUNT(*) AS EMPLOYEE_COUNT,
    AVG(SALARY) AS AVERAGE_SALARY
FROM HR.EMPLOYEES
GROUP BY IIF(COMMISSION_PCT IS NULL, 'No Commission', 'Commission')
ORDER BY AVERAGE_SALARY DESC;

SELECT 
    SUBSTRING (LAST_NAME, 1, 1) AS LAST_NAME_INITIAL,
    COUNT(*) AS EMPLOYEE_COUNT
FROM HR.EMPLOYEES
GROUP BY SUBSTRING (LAST_NAME, 1, 1)
ORDER BY LAST_NAME_INITIAL;

SELECT
    YEAR(HIRE_DATE) AS HIRE_YEAR,
    COUNT(*) AS EMPLOYEE_COUNT
FROM HR.EMPLOYEES
GROUP BY YEAR(HIRE_DATE)
ORDER BY HIRE_YEAR;

SELECT DEPARTMENT_ID, COUNT(*) AS DIFFERENT_COMMISSION_RATES
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL AND DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
ORDER BY DIFFERENT_COMMISSION_RATES DESC;

SELECT MANAGER_ID, COUNT(*) AS NUMBER_OF_REPORTS, MAX(SALARY) AS MAXIMUM_SALARY
FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NOT NULL
GROUP BY MANAGER_ID
HAVING COUNT(*) >= 3
ORDER BY COUNT(*) DESC;

SELECT JOB_ID
FROM HR.EMPLOYEES
WHERE SALARY BETWEEN 5000 AND 9999
GROUP BY JOB_ID;

