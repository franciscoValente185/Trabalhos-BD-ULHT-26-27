SELECT model_year, COUNT(*) AS PRODUCT_COUNT, MIN(list_price) AS min_price, MAX(list_price) AS max_price
FROM production.products
GROUP BY MODEL_YEAR;

SELECT CATEGORY_ID, COUNT(*) AS PRODUCT_COUNT, AVG(LIST_PRICE) AS AVG_PRICE
FROM production.products
GROUP BY category_id
ORDER BY AVG_PRICE DESC;

SELECT PRODUCT_NAME, COUNT(*) AS OCCORRENCE_COUNT
FROM production.products
GROUP BY product_name
HAVING COUNT(*) > 1
ORDER BY OCCORRENCE_COUNT DESC;

SELECT BRAND_ID, MODEL_YEAR, COUNT(*) AS PRODUCT_COUNT
FROM production.products
WHERE model_year IN (2016,2017)
GROUP BY brand_id, model_year
HAVING COUNT(*) > 5;

SELECT DISTINCT CATEGORY_ID, COUNT(DISTINCT list_price) AS DISTINCT_PRICE
FROM production.products
GROUP BY category_id
HAVING COUNT(DISTINCT list_price) >= 20;

