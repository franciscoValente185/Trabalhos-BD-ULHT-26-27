INTO production.vw_category_price_summary
FROM production.products
GROUP BY category_id;

SELECT * FROM production.vw_category_price_summary;

SELECT * FROM production.vw_category_price_summary
WHERE avg_price > (SELECT AVG(list_price) FROM production.products);

