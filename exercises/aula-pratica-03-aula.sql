--Exercício 1

SELECT Hire_Date, Employee_Id, Last_Name
FROM HR.EMPLOYEES
WHERE Hire_Date >= '2007-01-01'
ORDER BY Hire_Date;

--Exercício 2

SELECT DEPARTMENT_ID, SALARY
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 60 AND SALARY < 7000;

--Exercício 3

SELECT * FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (30, 100) AND SALARY >= 7000;

--Exercício 4

SELECT EMPLOYEE_ID, SALARY FROM HR.EMPLOYEES
WHERE SALARY NOT BETWEEN 5000 AND 10000
ORDER BY SALARY;

--Exercício 5

SELECT EMPLOYEE_ID, JOB_ID
FROM HR.EMPLOYEES
WHERE JOB_ID IN ('IT_PROG', 'FI_ACCOUNT', 'PU_CLERK');

--Exercício 6

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE '_A%'; 

--Exercício 7

SELECT EMPLOYEE_ID, DEPARTMENT_ID, FIRST_NAME, LAST_NAME, COMMISSION_PCT
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL AND COMMISSION_PCT IS NULL;

--Exercício 8

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE '[A-D]%'
ORDER BY LAST_NAME;

--Exercício 9

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY, HIRE_DATE,
       CASE
           WHEN HIRE_DATE < '2003-01-01' THEN 'Early'
           WHEN HIRE_DATE < '2006-01-01' THEN 'Middle'
           ELSE 'Recent'
       END AS Hire_Date_Category
FROM HR.EMPLOYEES
